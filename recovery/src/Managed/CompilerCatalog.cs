        }
        public static ExtendedTypeInformation TypeInformation(bool tokenizer, TargetPlatform platform, uint id) {
            var result = new ExtendedTypeInformation();
            result.TypeId = id;
            result.HasCustomData = false;
            result.Tokenized = tokenizer;
            foreach (var entry in tokenizer ? Tokenizer : XmlCompiler) {
                if (entry.Id != id) continue;
                result.TypeName = entry.Name;
                result.TypeHash = entry.Hash;
                result.ProcessingHash = tokenizer ? unchecked(Version(true, platform) + entry.Hash) : Version(false, platform) ^ entry.Hash;
                break;
            }
            return result;
        }
    }
