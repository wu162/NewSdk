#!/usr/bin/env python3
"""Generate UIConfig component layouts from fixed original marshaler evidence.
All original lookups must pair with exactly one supported field write; fail closed.
"""
from pathlib import Path
import json,re
ROOT=Path(__file__).resolve().parents[2]
E=ROOT/'recovery/evidence/xml-source'
source=''.join(p.read_text() for p in sorted((E/'parts').glob('part-*.cs.txt')))
strings={r['symbol']:bytes.fromhex(r['hex']).split(b'\0')[0].decode('latin1') for p in (E/'static-data').glob('fields-*.json') for r in json.loads(p.read_text()) if 'hex' in r}
index=json.loads((ROOT/'recovery/evidence/xml-uiconfiglist/contract-index.json').read_text())
def demangle(s):
 for a,b in [('_0020',' '),('_003A',':'),('_003C','<'),('_003E','>'),('_002C',','),('_002E','.')]:s=s.replace(a,b)
 return s

def compact(body):
 out=[]
 for line in body.splitlines():
  if any(s in line for s in ['IValue* ptr','NodeHolder*>)(int)','Marshaler_002EMarshal','strtol(','strtoul(','atof(','FindNVPair','?','@object =','@object)[']):
   line=re.sub(r'\(sbyte\*\)System.Runtime.CompilerServices.Unsafe.AsPointer\(ref ([^)]+)\)',lambda m:json.dumps(strings[m[1]]),line)
   line=re.sub(r'\(\(delegate\*.*?\)\)\(\(nint\)node, ', 'READ(',line)
   line=re.sub(r'\(\(delegate\*.*?\)\)\(\(nint\)ptr\d*\)', 'VALUE',line)
   out.append(demangle(line.strip()))
 return out

def offset(line):
 m=re.search(r'\(\(byte\*\)@object \+ (\d+)\)',line)
 if m:return int(m[1])
 m=re.search(r'\(\((?:int|float|uint)\*\)@object\)\[(\d+)\]',line)
 if m:return 4*int(m[1])
 m=re.search(r'\((int|float|uint|bool)\*\)@object \+ (\d+)',line)
 if m:return int(m[2])*(1 if m[1]=='bool' else 4)
 raise ValueError('Unrecognized field offset: '+line)

def fieldkind(line):
 if '(List<' in line:
  d=re.search(r'\(List<(.+?)>\*\)',line)[1]
  if 'TypedAssetId' in d:d='TypedAssetId'
  elif d=='Relo::AssetId':d='AssetId'
  elif 'String<char>' in d:d='String'
  else:d=d.replace('SageBinaryData::','').replace('enum ','')
  return 'list',d.strip()
 if '(ObjectFilter**)' in line:return 'nullable','ObjectFilter'
 if 'TypedAssetId<' in line:return ('nullableHash' if '>**)' in line else 'hash'),''
 if 'AssetReference<' in line:return ('nullableRef' if '>**)' in line else 'ref'),''
 if 'BitFlags<' in line:return 'flags',''
 if 'FastHashFn' in line:return 'rawhash',''
 if 'String<char>' in line or 'AssetId*)' in line:return 'string',''
 for t in ['RadiusDecalTemplate','DefaultValues','MultiplayerLobbyData','SkirmishLobbyData','Vector2','RGBColor','FontDesc']:
  if '('+t+'*)' in line:return 'inline',t
 if '&colorTag' in line:return 'inline','ColorTag'
 if 'strtoul(' in line or 'Marshal<unsigned int,' in line:return 'uint',''
 if 'strtol(' in line or 'Marshal<int,' in line:return 'int',''
 if 'atof(' in line or 'Marshal<float,' in line:return 'float',''
 if 'Marshal<bool,' in line:return 'bool',''
 raise ValueError('Unrecognized field kind: '+line)

methods={}
for m in re.finditer(r'^\s*internal (?:unsafe )?static [^\n]+',source,re.M):
 start=m.end();end=source.find('\n\tinternal ',start);methods[m.group().strip()]=source[start:end if end>=0 else len(source)]
layouts={}
for entry in index['dispatch']:
 name=entry['name']; sig=next((s for s in methods if f'(INode* node, {name}* @object, Tracker* state)' in s),None)
 if not sig:
  assert entry['marshalLine'] is None,name
  layouts[name]={'bytes':entry['bytes'],'fields':[]};continue
 fields=[];current=None;lookups=0
 for line in compact(methods[sig]):
  if 'READ(' in line:
   quotes=re.findall(r'"(?:\\.|[^"\\])*"',line);assert quotes,line
   assert current is None,(name,current,line)
   namefield=json.loads(quotes[0]);default=json.loads(quotes[1]) if len(quotes)>1 else None
   mode='child' if line.startswith('int num') or '(List<' in line else 'attr'
   current=dict(name=namefield,mode=mode,default=default);lookups+=1
  if '@object' not in line or 'UIBaseComponent*)' in line:continue
  if not ('Marshaler.Marshal' in line or '= ' in line):continue
  assert current is not None,(name,line)
  kind,dep=fieldkind(line);f=dict(current,offset=offset(line),kind=kind,dependency=dep,wrapper='')
  # Two decal wrappers and the official-map wrapper enumerate child elements.
  if kind=='list' and current['mode']=='child' and 'READ(' not in line:
   quotes=re.findall(r'"(?:\\.|[^"\\])*"',line)
   assert len(quotes)==1,(name,line)
   f['wrapper']=json.loads(quotes[0])
  fields.append(f);current=None
 assert current is None,(name,current)
 assert lookups==len(fields),(name,lookups,len(fields))
 layouts[name]={'bytes':entry['bytes'],'fields':fields}
# Every known specialized original method has been traversed, not inferred from schema.
assert sum(bool(x['fields']) for x in layouts.values())==47
assert sum(len(x['fields']) for x in layouts.values())==288
out=['// Generated by GenerateXmluiconfigComponents.py from fixed original Marshal methods.', '// Source Module blob 2d2f471c8008b7c2e1f78e39752d0726da395cea.']
q=lambda s:'nullptr' if s is None else json.dumps(s)
for name,d in layouts.items():
 out+=['void '+name+'(const Node& n,unsigned char* p){']
 for f in d['fields']:
  a=q(f['name']);at='p+'+str(f['offset']);default=q(f['default']);kind=f['kind'];dep=q(f['dependency'])
  if f['mode']=='attr':
   if kind in ['int','uint','float','bool']:code=f'Scalar(n,{a},{at},{q(kind)},{default});'
   elif kind=='string':code=f'String(n,{a},{at},{default});'
   elif kind=='hash':code=f'Hash(n,{a},{at},{default});'
   elif kind=='rawhash':code=f'{{auto a=n.attributes.find({a});if(a!=n.attributes.end())Word({at},RawHash(a->second));}}'
   elif kind=='ref':code=f'Ref(n,{a},{at},{default});'
   elif kind=='nullableHash':code=f'NullableHash(n,{a},{at});'
   elif kind=='nullableRef':code=f'NullableRef(n,{a},{at});'
   elif kind=='flags':code=f'KindFlags(n,{a},{at});'
   else:raise ValueError(f)
  elif kind=='list':
   if f['wrapper']:code=f'{{auto c=Child(n,{a});if(c){{NamedList(*c,{q(f["wrapper"])},{at},{dep});}}}}'
   else:code=f'NamedList(n,{a},{at},{dep});'
  elif kind=='inline':code=f'{{auto c=Child(n,{a});if(c)Marshal({dep},*c,{at});}}'
  elif kind=='nullable':code=f'Nullable(n,{a},{at},{dep});'
  elif kind=='string':code=f'NestedChildString(n,{a},{at});'
  elif kind in ['int','uint','float','bool']:code=f'{{auto c=Child(n,{a});if(c){{'+ ('*('+at+')=ParseBoolean(c->value);' if kind=='bool' else ('Real' if kind=='float' else 'Word')+f'({at},'+{'float':'ParseFloat','int':'ParseSigned','uint':'ParseUnsigned'}[kind]+'(c->value));')+'}}'
  else:raise ValueError(f)
  out.append(' '+code)
 out+=[' Scalar(n,"Priority",p+4,"int");','}']
out+=['unsigned ComponentSize(U32 type){switch(type){']
for e in index['dispatch']:out.append(f' case {e["typeId"]}u:return {e["bytes"]};')
out+=[' default:return 8;}}','void Dispatch(U32 type,const Node& n,unsigned char* p){switch(type){']
for e in index['dispatch']:out.append(f' case {e["typeId"]}u:{e["name"]}(n,p);Word(p,{e["typeId"]}u);return;')
out+=[' default:Scalar(n,"Priority",p+4,"int");Word(p,0);return;}}']
(ROOT/'recovery/src/Native/XmluiconfigComponents.inc').write_text('\n'.join(out)+'\n')
(ROOT/'recovery/evidence/xml-uiconfiglist/component-layouts.json').write_text(json.dumps(layouts,indent=2)+'\n')
print('Generated70 branches,47 specialized layouts,288 fields; all original input lookups paired.')
