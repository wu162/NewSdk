#!/usr/bin/env python3
"""Recover Joypad root/polymorphic allocation sizes and enum maps from fixed evidence."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EVIDENCE = ROOT / 'recovery/evidence/xml-source'
source = ''.join(p.read_text() for p in sorted((EVIDENCE / 'parts').glob('part-*.cs.txt')))
methods = {}
for match in re.finditer(r'^\s*internal (?:unsafe )?static [^\n]+', source, re.M):
    end = source.find('\n\tinternal ', match.end())
    methods[match.group().strip()] = source[match.end():end if end >= 0 else len(source)]

def demangle(value):
    for a, b in [('_0020', ' '), ('_003A', ':'), ('_003C', '<'), ('_003E', '>'), ('_002C', ','), ('_002E', '.')]:
        value = value.replace(a, b)
    return value

roots = []
catalog = (ROOT / 'recovery/src/Managed/CompilerCatalog.cs').read_text()
for item in re.finditer(r'new Entry\((\d+)u, "([^"]*Joypad[^"]*)", (\d+)u\)', catalog):
    type_id, name, type_hash = item.groups()
    struct = (ROOT / 'recovery/decompiled/BinaryAssetBuilder.XmlCompiler/SageBinaryData' / (name + '.cs')).read_text()
    size = int(re.search(r'Size = (\d+)', struct)[1])
    roots.append(dict(name=name, typeId=int(type_id), typeHash=int(type_hash), bytes=size))
assert len(roots) == 11

payloads = []
for signature, body in methods.items():
    if 'Marshaler_002EMarshalPolymorphicType_' not in signature or '_003AJoypadCommandBarButtonTemplateData' not in signature:
        continue
    name = re.search(r'SageBinaryData::(Joypad[^,]+)', demangle(signature))[1]
    size = int(re.search(r'Push\(tracker, \(void\*\*\)pointer, (\d+)u', demangle(body))[1])
    type_id = int(re.search(r'\*\(int\*\)(?:ptr|intPtr) = (-?\d+);', body)[1]) & 0xffffffff
    payloads.append(dict(name=name, typeId=type_id, bytes=size))
assert len(payloads) == 34 and len({p['typeId'] for p in payloads}) == 34

enum_names = ['ProductionQueueType', 'OutlineDrawType', 'Stance', 'AIStrategicDirective', 'CommandMode', 'FactionType']
enums = {name: json.loads((EVIDENCE / 'enums' / (name + '.json')).read_text())['entries'] for name in enum_names}
lines = ['// Generated by GenerateXmlJoypadLayouts.py from the original XmlCompiler evidence.',
         '// Original Module blob: 2d2f471c8008b7c2e1f78e39752d0726da395cea.',
         'const RootLayout Roots[] = {']
lines += ['    {"%s", %su, %s},' % (r['name'], r['typeId'], r['bytes']) for r in roots]
lines += ['};', 'const PayloadLayout Payloads[] = {']
lines += ['    {%su, %s}, // %s' % (p['typeId'], p['bytes'], p['name']) for p in payloads]
lines += ['};']
for name, entries in enums.items():
    lines += ['const EnumEntry ' + name + 'Values[] = {']
    lines += ['    {%s, %s},' % (json.dumps(e['name']), e['value']) for e in entries]
    lines += ['};']
(ROOT / 'recovery/src/Native/XmljoypadLayouts.inc').write_text('\n'.join(lines) + '\n')
print('Generated %s roots, %s polymorphic layouts and %s enum maps.' % (len(roots), len(payloads), len(enums)))
